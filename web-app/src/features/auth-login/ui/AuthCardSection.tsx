"use client";

import { Badge } from "@/shared/ui";
import { useAuthState } from "../model/authStore";
import { LoginForm } from "./LoginForm";
import { ForceSetupForm } from "./ForceSetupForm";
import { TwoFactorVerifyForm } from "./TwoFactorVerifyForm";
import styles from "./split.module.css";

export function AuthCardSection() {
  const authState = useAuthState();

  const isForceSetup = authState.type === "force_password_change";
  const is2FARequired = authState.type === "two_factor_required";

  return (
    <section
      className={`${styles.cardSection} ${isForceSetup ? styles.cardSectionSetup : ""}`}
      aria-label="Sign in form"
    >
      <div className={`${styles.cardInner} ${isForceSetup ? styles.cardInnerSetup : ""}`}>
        <div className={styles.cardHeader}>
          <div className={styles.cardHeaderTop}>
            <h1 className={styles.cardTitle}>
              {isForceSetup
                ? "Mandatory Security Setup"
                : is2FARequired
                ? "Two-Factor Verification"
                : "Institutional Sign In"}
            </h1>
            <Badge variant="amber">
              {isForceSetup
                ? "Initial Setup"
                : is2FARequired
                ? "2FA Required"
                : "Authorized Personnel"}
            </Badge>
          </div>
          <p className={styles.cardSubtitle}>
            {isForceSetup
              ? "Set your permanent institutional credentials and link your authenticator app before accessing the platform."
              : is2FARequired
              ? "Enter the 6-digit verification code generated by your authenticator app."
              : "Provide your institutional security credentials to access the administrative console."}
          </p>
        </div>

        {isForceSetup ? (
          <ForceSetupForm />
        ) : is2FARequired ? (
          <TwoFactorVerifyForm />
        ) : (
          <LoginForm />
        )}

        <div className={styles.cardFooter}>
          <span className={styles.attributionDiamond} aria-hidden="true" />
          <span>
            Engineering Standard:{" "}
            <strong className={styles.attributionBold}>
              Powered by <span className={styles.brandAccent}>Barkat Tech</span>
            </strong>
          </span>
        </div>
      </div>
    </section>
  );
}
